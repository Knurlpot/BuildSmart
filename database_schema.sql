-- =====================================================
-- 15. Segment Tag
-- =====================================================
CREATE TABLE segment_tag (
    tag_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segment_id INT NOT NULL,
    tag_type VARCHAR(20) NOT NULL CHECK (tag_type IN ('Preference', 'Condition')),
    tag_value VARCHAR(40) NOT NULL CHECK (
        (tag_type = 'Preference' AND tag_value IN ('Durability', 'Cost Efficiency', 'Aesthetic Finish', 'Low-Maintenance', 'Eco-Friendly'))
        OR
        (tag_type = 'Condition' AND tag_value IN ('Heavy-Rain Exposure', 'High Foot Traffic', 'Crack-prone Surface', 'Moisture Prone Area'))
    ),
    CONSTRAINT fk_segment_tag_segment FOREIGN KEY (segment_id) REFERENCES project_segments(segment_id) ON DELETE CASCADE,
    CONSTRAINT uq_segment_tag UNIQUE (segment_id, tag_type, tag_value)
);


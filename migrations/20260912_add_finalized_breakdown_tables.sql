CREATE TABLE IF NOT EXISTS quotation_breakdown_snapshot (
    breakdown_snapshot_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id INT NOT NULL UNIQUE,
    tier VARCHAR(20) NOT NULL CHECK (tier IN ('Practical', 'Premium')),
    pricelist_basis VARCHAR(20) NOT NULL CHECK (pricelist_basis IN ('Uploaded', 'DPWH')),
    materials_subtotal DECIMAL(15,2) NOT NULL DEFAULT 0 CHECK (materials_subtotal >= 0),
    labor_cost DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (labor_cost >= 0),
    rush_job_cost DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (rush_job_cost >= 0),
    equipment_cost DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (equipment_cost >= 0),
    contingency_cost DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (contingency_cost >= 0),
    other_cost DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (other_cost >= 0),
    service_subtotal DECIMAL(15,2) NOT NULL DEFAULT 0 CHECK (service_subtotal >= 0),
    ocm_percentage DECIMAL(7,4) NOT NULL DEFAULT 0,
    ocm_amount DECIMAL(15,2) NOT NULL DEFAULT 0 CHECK (ocm_amount >= 0),
    profit_margin_percentage DECIMAL(7,4) NOT NULL DEFAULT 0,
    profit_amount DECIMAL(15,2) NOT NULL DEFAULT 0 CHECK (profit_amount >= 0),
    subtotal_before_vat DECIMAL(15,2) NOT NULL DEFAULT 0 CHECK (subtotal_before_vat >= 0),
    vat_rate_percentage DECIMAL(7,4) NOT NULL DEFAULT 0,
    vat_taxable_base DECIMAL(15,2) NOT NULL DEFAULT 0 CHECK (vat_taxable_base >= 0),
    vat_amount DECIMAL(15,2) NOT NULL DEFAULT 0 CHECK (vat_amount >= 0),
    vat_inclusive BOOLEAN NOT NULL DEFAULT FALSE,
    grand_total DECIMAL(15,2) NOT NULL DEFAULT 0 CHECK (grand_total >= 0),
    timeline_label VARCHAR(100) NOT NULL DEFAULT '',
    warranty_label VARCHAR(100) NOT NULL DEFAULT '',
    lifespan_label VARCHAR(100) NOT NULL DEFAULT '',
    material_grade_label VARCHAR(100) NOT NULL DEFAULT '',
    finalized_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_breakdown_snapshot_quote FOREIGN KEY (quote_id) REFERENCES quotation(quote_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS quotation_breakdown_items (
    breakdown_item_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id INT NOT NULL,
    line_id VARCHAR(120) NOT NULL,
    segment_draft_id VARCHAR(120) NOT NULL,
    segment_name VARCHAR(120) NOT NULL,
    floor_level VARCHAR(80) NOT NULL,
    treatment_type VARCHAR(120),
    category VARCHAR(20) NOT NULL CHECK (category IN ('Material', 'Labor')),
    item_code VARCHAR(80) NOT NULL,
    item_name VARCHAR(255) NOT NULL,
    unit VARCHAR(40) NOT NULL,
    derived_area_sqm DECIMAL(12,2),
    derived_coverage_per_sqm DECIMAL(12,4),
    derived_wastage_percentage DECIMAL(7,4),
    quantity DECIMAL(12,4) NOT NULL CHECK (quantity >= 0),
    unit_price DECIMAL(12,2),
    total_cost DECIMAL(15,2),
    source_type VARCHAR(20) NOT NULL CHECK (source_type IN ('Uploaded', 'DPWH')),
    is_overridden BOOLEAN NOT NULL DEFAULT FALSE,
    price_source VARCHAR(20) NOT NULL CHECK (price_source IN ('DPWH', 'PSA', 'Supplier', 'Internal')),
    region VARCHAR(30),
    brand VARCHAR(120),
    quarter VARCHAR(2) CHECK (quarter IN ('Q1', 'Q2', 'Q3', 'Q4')),
    year INT,
    recorded_at TIMESTAMP,
    labor_rule_scope VARCHAR(20) CHECK (labor_rule_scope IN ('Treatment', 'Trade', 'General')),
    labor_rule_label VARCHAR(120),
    worker_count INT,
    rush_multiplier_percentage DECIMAL(7,4),
    productivity_index DECIMAL(7,4),
    selected_supplier_id INT,
    selected_supplier_name VARCHAR(150),
    CONSTRAINT fk_breakdown_items_quote FOREIGN KEY (quote_id) REFERENCES quotation(quote_id) ON DELETE CASCADE,
    CONSTRAINT uq_breakdown_item_line UNIQUE (quote_id, line_id)
);

CREATE INDEX IF NOT EXISTS ix_breakdown_items_quote ON quotation_breakdown_items(quote_id);

CREATE TABLE IF NOT EXISTS quotation_breakdown_supplier_options (
    breakdown_supplier_option_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id INT NOT NULL,
    line_id VARCHAR(120) NOT NULL,
    supplier_id INT NOT NULL,
    supplier_name VARCHAR(150) NOT NULL,
    brand VARCHAR(120),
    location VARCHAR(150),
    unit_price DECIMAL(12,2) NOT NULL CHECK (unit_price >= 0),
    original_unit_price DECIMAL(12,2),
    quantity_available DECIMAL(12,2),
    source_type VARCHAR(20) NOT NULL CHECK (source_type IN ('Uploaded', 'DPWH')),
    CONSTRAINT fk_breakdown_supplier_options_quote FOREIGN KEY (quote_id) REFERENCES quotation(quote_id) ON DELETE CASCADE,
    CONSTRAINT uq_breakdown_supplier_option UNIQUE (quote_id, line_id, supplier_id)
);

CREATE INDEX IF NOT EXISTS ix_breakdown_supplier_options_quote_line
    ON quotation_breakdown_supplier_options(quote_id, line_id);
